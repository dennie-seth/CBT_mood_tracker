from __future__ import annotations

import re

from app.bot.i18n import metric_label
from app.domain.enums import NUMERIC_METRICS, TEXT_METRICS, MetricType, metric_semantics_block


def _metric_glossary_block() -> str:
    """metric_type → the English and Russian names the bot shows the user,
    so replies use the same words as the buttons and confirmations.
    Generated (not hand-written) so it can't drift from the i18n tables."""
    lines = []
    for m in MetricType:
        if m not in NUMERIC_METRICS and m not in TEXT_METRICS:
            continue
        en = re.sub(r"\s*\(.*?\)", "", metric_label(m, "en"))
        ru = re.sub(r"\s*\(.*?\)", "", metric_label(m, "ru"))
        lines.append(f"- {m.value}: “{en}” / «{ru}»")
    return "\n".join(lines)


